// ---------- Помощники ----------
const R = (x, y, w, h, m, o) => ({ shape: "rect", x, y, w, h, m: m || "ground", ...o });
const P = (pts, m, o) => ({ shape: "poly", pts, m: m || "ground", ...o });
const floor = (y, x0 = -400, x1 = 1680, m) => R(x0, y, x1 - x0, 1000 - y, m);
// Склон от (x0, y0) к (x1, y1), залитый до самого низа
const slope = (x0, y0, x1, y1, m) => P([[x0, y0], [x1, y1], [x1, 1000], [x0, 1000]], m);
// Купол над точкой: концы на высоте lift над землёй
const dome = (x, foot, rx, ry = rx, lift = 12) => arc(x, foot - lift, rx, ry, 180, 360, 20);
const line = (...pts) => pts;

