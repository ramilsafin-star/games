// Трассы «Гонки бобрят». road — середина дороги по островам (по ней бобрята бегут сами),
// islands — [x, y, радиус] островки, piles — кучи брёвнышек, gates — ворота (y), shortcuts — срезки для ботов.
// Ширина карты 22 клетки; y растёт вперёд, от старта к финишу.

// Петля дороги вбок: дорога уходит вправо (side 1) или влево (−1) и возвращается — вода посередине
function loop(x, y, side, wide = 7, tall = 7) {
  return [
    [x, y],
    [x + side * wide, y + 1],
    [x + side * wide, y + tall - 1],
    [x, y + tall],
  ];
}

