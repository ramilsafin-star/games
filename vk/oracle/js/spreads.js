// draws — [{ card, reversed, text }] в порядке позиций; texts — словарь толкований по id
export function detailReading(spread, draws, texts) {
  const parts = [];
  const majors = draws.filter((d) => d.card.arcana === "major").length;
  const share = majors / draws.length;
  if (draws.length > 1) {
    parts.push(MAJOR_THEME[majors === 0 ? 0 : majors === 1 ? 1 : share > 0.5 ? 3 : 2]);
    const suits = {};
    for (const d of draws) if (d.card.arcana !== "major") suits[d.card.arcana] = (suits[d.card.arcana] || 0) + 1;
    const top = Object.entries(suits).sort((a, b) => b[1] - a[1]);
    if (top.length && top[0][1] >= 2 && (top.length === 1 || top[0][1] > top[1][1])) parts.push(SUIT_THEME[top[0][0]]);
    const revs = draws.filter((d) => d.reversed).length;
    parts.push(REV_THEME[revs === 0 ? 0 : revs > draws.length / 2 ? 2 : 1]);
    if (draws.some((d) => d.card.arcana !== "major" && d.card.n > 10)) parts.push(COURT_THEME);
    const ranks = {};
    for (const d of draws) if (d.card.arcana !== "major" && d.card.n <= 10) ranks[d.card.n] = (ranks[d.card.n] || 0) + 1;
    for (const [n, k] of Object.entries(ranks)) if (k >= 2) parts.push(NUMBER_THEME[n]);
  }
  // Каждая карта в своей сфере: любовь — для «Отношений», работа — для «Работы и денег», для остальных — обе
  const facets = spread.facet === "love" ? ["love"] : spread.facet === "work" ? ["work"] : ["love", "work"];
  const cards = draws.map((d, i) => ({
    pos: spread.pos[i].name,
    name: d.card.name,
    lines: facets.map((f) => [f === "love" ? "В отношениях" : "В делах", texts[d.card.id][f]]),
  }));
  const last = draws[draws.length - 1];
  const element = last.card.arcana === "major" ? null : SUITS[last.card.arcana].element;
  return {
    theme: parts,
    cards,
    advice: texts[last.card.id].advice,
    element,
  };
}
