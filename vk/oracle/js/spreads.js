// Ответ «да или нет»: прямая карта отвечает своим yes, перевёрнутая смягчает «да» до «пока неясно»
export function yesNo(yes, reversed) {
  const v = reversed && yes === 1 ? 0 : yes;
  return { v, label: v > 0 ? "Да" : v < 0 ? "Скорее нет" : "Пока неясно" };
}

// Границы раскладки (для подбора размера карт под стол)
export function bounds(spread) {
  let x0 = Infinity,
    x1 = -Infinity,
    y0 = Infinity,
    y1 = -Infinity;
  for (const p of spread.pos) {
    const hw = p.cross ? 0.75 : 0.5,
      hh = p.cross ? 0.5 : 0.75;
    x0 = Math.min(x0, p.x - hw);
    x1 = Math.max(x1, p.x + hw);
    y0 = Math.min(y0, p.y - hh);
    y1 = Math.max(y1, p.y + hh);
  }
  return { x0, x1, y0, y1, w: x1 - x0, h: y1 - y0 };
}

